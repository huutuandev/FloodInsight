"""Keep calibrated flood probabilities in their own registry kind and result table."""

from alembic import op

revision = "0008"
down_revision = "0007"
branch_labels = None
depends_on = None


def upgrade():
    op.drop_constraint(op.f("ck_model_versions_kind"), "model_versions", type_="check")
    op.create_check_constraint(op.f("ck_model_versions_kind"), "model_versions",
                               "kind IN ('clustering', 'prediction', 'classification', 'flood')")
    op.execute("""
        CREATE TABLE flood_probability_results (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            model_version_id bigint NOT NULL,
            model_kind varchar(16) NOT NULL DEFAULT 'flood' CHECK (model_kind = 'flood'),
            location_id bigint NOT NULL REFERENCES dim_location,
            issued_at timestamptz NOT NULL,
            valid_until timestamptz NOT NULL CHECK (valid_until = issued_at + interval '24 hours'),
            probability double precision NOT NULL CHECK (probability BETWEEN 0 AND 1),
            input_sha256 text NOT NULL CHECK (input_sha256 ~ '^[0-9a-f]{64}$'),
            result jsonb NOT NULL CHECK (jsonb_typeof(result) = 'object'),
            created_at timestamptz NOT NULL DEFAULT now(),
            FOREIGN KEY (model_version_id, model_kind) REFERENCES model_versions (id, kind),
            UNIQUE (model_version_id, location_id, issued_at, input_sha256)
        )
    """)


def downgrade():
    # Reinstating the older registry check will fail if flood model versions still exist.
    op.drop_table("flood_probability_results")
    op.drop_constraint(op.f("ck_model_versions_kind"), "model_versions", type_="check")
    op.create_check_constraint(op.f("ck_model_versions_kind"), "model_versions",
                               "kind IN ('clustering', 'prediction', 'classification')")
